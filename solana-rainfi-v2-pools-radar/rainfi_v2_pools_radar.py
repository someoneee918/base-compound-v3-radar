def calculate_pool_utilization_and_compounding_yield(
    pool_deposit_sol: float,
    active_borrowed_sol: float,
    base_borrow_apr_pct: float,
    protocol_take_rate_pct: float = 10.0,
    compounding_frequency: int = 52 # Weekly compounding
) -> Dict[str, Any]:
    """
    Calculates pool utilization rate, gross interest revenue, net lender APR after protocol fee,
    and effective compounding APY for automated collection-wide lending pools.
    """
    if pool_deposit_sol <= 0 or base_borrow_apr_pct <= 0:
        raise ValueError("Pool deposit and borrow APR must be positive.")

    active_borrowed_clamped = min(pool_deposit_sol, max(0.0, active_borrowed_sol))
    utilization_rate_pct = (active_borrowed_clamped / pool_deposit_sol) * 100.0
    utilization_ratio = utilization_rate_pct / 100.0

    # Gross annual interest generated by active loans
    gross_annual_interest_sol = active_borrowed_clamped * (base_borrow_apr_pct / 100.0)
    # Net interest distributed to pool depositors after protocol take-rate
    net_annual_interest_sol = gross_annual_interest_sol * (1.0 - (protocol_take_rate_pct / 100.0))

    # Net APR earned across total deposited pool capital
    net_lender_apr_pct = (net_annual_interest_sol / pool_deposit_sol) * 100.0

    # Compounding APY: (1 + r/n)^n - 1
    if net_lender_apr_pct > 0 and compounding_frequency > 0:
        periodic_rate = (net_lender_apr_pct / 100.0) / compounding_frequency
        net_lender_apy_pct = ((1.0 + periodic_rate) ** compounding_frequency - 1.0) * 100.0
    else:
        net_lender_apy_pct = net_lender_apr_pct

    daily_interest_sol = net_annual_interest_sol / 365.0

    return {
        "pool_deposit_sol": round(pool_deposit_sol, 2),
        "active_borrowed_sol": round(active_borrowed_clamped, 2),
        "utilization_rate_pct": round(utilization_rate_pct, 2),
        "base_borrow_apr_pct": round(base_borrow_apr_pct, 2),
        "protocol_take_rate_pct": round(protocol_take_rate_pct, 2),
        "net_annual_interest_sol": round(net_annual_interest_sol, 4),
        "daily_interest_sol": round(daily_interest_sol, 4),
        "net_lender_apr_pct": round(net_lender_apr_pct, 2),
        "net_lender_apy_pct": round(net_lender_apy_pct, 2)
    }

def calculate_refinancing_arbitrage_and_ltv_buffer(
    current_loan_principal_sol: float,
    collateral_floor_price_sol: float,
    current_loan_apr_pct: float,
    new_offer_apr_pct: float,
    remaining_duration_days: int
) -> Dict[str, Any]:
    """
    Evaluates loan refinancing economics: interest cost savings and safety LTV buffer before foreclosure.
    """
    if current_loan_principal_sol <= 0 or collateral_floor_price_sol <= 0 or remaining_duration_days <= 0:
        raise ValueError("Principal, collateral price, and duration must be positive.")

    current_ltv_pct = (current_loan_principal_sol / collateral_floor_price_sol) * 100.0
    ltv_safety_buffer_pct = max(0.0, 100.0 - current_ltv_pct)

    # Calculate interest costs over remaining duration
    duration_fraction = remaining_duration_days / 365.0
    old_interest_cost_sol = current_loan_principal_sol * (current_loan_apr_pct / 100.0) * duration_fraction
    new_interest_cost_sol = current_loan_principal_sol * (new_offer_apr_pct / 100.0) * duration_fraction

    interest_savings_sol = max(0.0, old_interest_cost_sol - new_interest_cost_sol)
    savings_pct = (interest_savings_sol / old_interest_cost_sol * 100.0) if old_interest_cost_sol > 0 else 0.0

    is_refinance_profitable = new_offer_apr_pct < current_loan_apr_pct

    return {
        "current_loan_principal_sol": round(current_loan_principal_sol, 3),
        "collateral_floor_price_sol": round(collateral_floor_price_sol, 3),
        "current_ltv_pct": round(current_ltv_pct, 2),
        "ltv_safety_buffer_pct": round(ltv_safety_buffer_pct, 2),
        "old_interest_cost_sol": round(old_interest_cost_sol, 4),
        "new_interest_cost_sol": round(new_interest_cost_sol, 4),
        "interest_savings_sol": round(interest_savings_sol, 4),
        "savings_pct": round(savings_pct, 2),
        "is_refinance_profitable": is_refinance_profitable
    }

def calculate_default_liquidation_auction_recovery(
    loan_principal_sol: float,
    accumulated_interest_sol: float,
    auction_settlement_price_sol: float,
    liquidator_bonus_pct: float = 5.0
) -> Dict[str, Any]:
    """
    Models foreclosure auction recovery when borrower defaults.
    """
    total_debt_owed_sol = loan_principal_sol + accumulated_interest_sol
    liquidator_fee_sol = auction_settlement_price_sol * (liquidator_bonus_pct / 100.0)
    net_proceeds_sol = max(0.0, auction_settlement_price_sol - liquidator_fee_sol)

    lender_recovered_sol = min(total_debt_owed_sol, net_proceeds_sol)
    borrower_surplus_sol = max(0.0, net_proceeds_sol - total_debt_owed_sol)
    bad_debt_shortfall_sol = max(0.0, total_debt_owed_sol - net_proceeds_sol)
    lender_recovery_rate_pct = (lender_recovered_sol / total_debt_owed_sol) * 100.0 if total_debt_owed_sol > 0 else 100.0

    return {
        "total_debt_owed_sol": round(total_debt_owed_sol, 4),
        "auction_settlement_price_sol": round(auction_settlement_price_sol, 4),
        "liquidator_fee_sol": round(liquidator_fee_sol, 4),
        "net_proceeds_sol": round(net_proceeds_sol, 4),
        "lender_recovered_sol": round(lender_recovered_sol, 4),
        "borrower_surplus_sol": round(borrower_surplus_sol, 4),
        "bad_debt_shortfall_sol": round(bad_debt_shortfall_sol, 4),
        "lender_recovery_rate_pct": round(lender_recovery_rate_pct, 2)
    }

